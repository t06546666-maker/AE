const assert = require('node:assert/strict');
const { createReadCache } = require('../backend/read-cache.cjs');
(async () => {
  let time = 0, calls = 0;
  const cache = createReadCache({ ttlMs: 30, maxEntries: 2, now: () => time, cacheable: Boolean });
  const load = async () => ++calls;
  assert.deepEqual(await Promise.all([cache.get('a', load), cache.get('a', load)]), [1, 1]);
  assert.equal(await cache.get('a', load), 1);
  time = 31;
  assert.equal(await cache.get('a', load), 2);
  cache.delete('a');
  assert.equal(await cache.get('a', load), 3);
  await assert.rejects(cache.get('error', async () => { throw Error('offline'); }));
  assert.equal(await cache.get('error', async () => 'recovered'), 'recovered');
  assert.equal(await cache.get('empty', async () => ''), '');
  assert.equal(await cache.get('empty', async () => 'retry'), 'retry');
  await cache.get('b', load);
  await cache.get('c', load);
  assert.equal(await cache.get('b', async () => 'wrong'), 4);
  let finish;
  const pending = cache.get('race', () => new Promise(resolve => { finish = resolve; }));
  await Promise.resolve();
  cache.delete('race');
  assert.equal(await cache.get('race', async () => 'new'), 'new');
  finish('old');
  await pending;
  assert.equal(await cache.get('race', async () => 'wrong'), 'new');
  console.log('Read cache: coalescing, expiry, invalidation, failures, bounds and race passed.');
})().catch(error => { console.error(error); process.exitCode = 1; });
