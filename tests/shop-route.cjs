const assert = require('node:assert/strict'), fs = require('node:fs'), vm = require('node:vm'), ts = require('typescript');
const scope = { exports: {}, URLSearchParams };
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/shopRoute.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, scope);
const { selectedShopRoute, hasShopLocation, shopRouteLinks } = scope.exports;
const shops = [{ id: 'a', name: 'Shop A', latitude: 10, longitude: 76 }, { id: 'b', name: 'Shop B', latitude: 11, longitude: 77 }, { id: 'c', name: 'Shop C', latitude: 12, longitude: 78 }];
const route = JSON.parse(JSON.stringify(selectedShopRoute(['c', 'a', 'b'], shops)));
assert.deepEqual(route.map(shop => shop.id), ['c', 'a', 'b']);
assert.throws(() => selectedShopRoute(['a'], shops));
assert.throws(() => selectedShopRoute(['a', 'a'], shops));
assert.throws(() => selectedShopRoute(['a', 'deleted'], shops));
assert.equal(hasShopLocation({ id: 'x', name: 'Missing', latitude: null, longitude: 76 }), false);
assert.equal(hasShopLocation({ id: 'x', name: 'Out of range', latitude: 91, longitude: 76 }), false);
assert.equal(hasShopLocation({ id: 'x', name: 'Zero is valid', latitude: 0, longitude: 0 }), true);
const links = shopRouteLinks(['c', 'a', 'b'], shops);
const link = new URL(links[0].url);
assert.equal(link.hostname, 'www.google.com');
assert.equal(link.searchParams.get('origin'), '12,78');
assert.equal(link.searchParams.get('destination'), '11,77');
assert.equal(link.searchParams.get('waypoints'), '10,76');
const many = Array.from({ length: 27 }, (_, index) => ({ id: String(index), name: String(index), latitude: index, longitude: index }));
const sections = shopRouteLinks(many.map(shop => shop.id), many);
assert.equal(sections.length, 7);
assert.equal(sections[0].from, 1);
assert.equal(sections[6].to, 27);
for (let index = 1; index < sections.length; index++) assert.equal(sections[index].from, sections[index - 1].to);
for (const section of sections) assert.ok((new URL(section.url).searchParams.get('waypoints') || '').split('|').filter(Boolean).length <= 3);
console.log('PASS: driving links preserve chosen stop order; invalid, deleted and duplicate stops rejected; all stops retained across mobile route sections. No route API called.');
