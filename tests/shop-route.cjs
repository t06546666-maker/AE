const assert = require('node:assert/strict'), fs = require('node:fs'), vm = require('node:vm'), ts = require('typescript');
const scope = { exports: {} };
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/shopRoute.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, scope);
const { shopDrivingRoute, hasShopLocation } = scope.exports;
const shops = [{ id: 'a', name: 'Shop A', latitude: 10, longitude: 76 }, { id: 'b', name: 'Shop B', latitude: 11, longitude: 77 }, { id: 'c', name: 'Shop C', latitude: 12, longitude: 78 }];
const route = JSON.parse(JSON.stringify(shopDrivingRoute(['c', 'a', 'b'], shops)));
assert.deepEqual(route.origin, { lat: 12, lng: 78 });
assert.deepEqual(route.destination, { lat: 11, lng: 77 });
assert.deepEqual(route.waypoints, [{ location: { lat: 10, lng: 76 }, stopover: true }]);
assert.equal(route.optimizeWaypoints, false);
assert.equal(route.travelMode, 'DRIVING');
assert.throws(() => shopDrivingRoute(['a'], shops));
assert.throws(() => shopDrivingRoute(['a', 'a'], shops));
assert.throws(() => shopDrivingRoute(['a', 'deleted'], shops));
assert.throws(() => shopDrivingRoute(Array.from({ length: 28 }, (_, i) => String(i)), shops));
assert.equal(hasShopLocation({ id: 'x', name: 'Missing', latitude: null, longitude: 76 }), false);
assert.equal(hasShopLocation({ id: 'x', name: 'Out of range', latitude: 91, longitude: 76 }), false);
assert.equal(hasShopLocation({ id: 'x', name: 'Zero is valid', latitude: 0, longitude: 0 }), true);
console.log('PASS: driving request preserves chosen stop order; invalid, deleted, duplicate and excessive stops rejected. No Google route service called.');
